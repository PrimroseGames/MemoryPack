using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Text;

namespace MemoryPack.Generator;

// Registers, at module load, the formatter for every closed type the assembly passes to a MemoryPack
// Serialize/Deserialize/ReadValue/WriteValue call, and for the types nested inside it. Without this
// a top-level List<T>, Dictionary<K,V> or T[] nobody registered is only found by building its
// formatter at runtime, which NativeAOT can't do for an instantiation it didn't compile.
//
// The formatters are the ones the runtime would pick, so the bytes are the same. Types without
// references are left alone: the runtime copies those as they are, padding included, and a
// formatter chosen here could differ (an unmanaged KeyValuePair, for one).
partial class MemoryPackGenerator
{
    static readonly HashSet<string> CallSiteMethodNames = new() { "Serialize", "Deserialize", "SerializeAsync", "DeserializeAsync", "ReadValue", "WriteValue" };
    static readonly HashSet<string> CallSiteContainingTypes = new() { "MemoryPackSerializer", "MemoryPackReader", "MemoryPackWriter" };

    void RegisterCallSiteRegistration(IncrementalGeneratorInitializationContext context)
    {
        var callSiteTypes = context.SyntaxProvider.CreateSyntaxProvider(
                predicate: static (node, token) => node is InvocationExpressionSyntax invocation && InvokedName(invocation.Expression) is { } name && CallSiteMethodNames.Contains(name),
                transform: static (context, token) =>
                {
                    if (context.SemanticModel.GetSymbolInfo(context.Node, token).Symbol is not IMethodSymbol method) return null;
                    if (!method.IsGenericMethod || method.TypeArguments.Length == 0) return null;

                    var containing = method.ContainingType;
                    if (containing == null || containing.ContainingNamespace?.ToDisplayString() != "MemoryPack" || !CallSiteContainingTypes.Contains(containing.Name)) return null;

                    return method.TypeArguments[0];
                })
            .Where(static x => x != null)
            .Collect()
            .WithTrackingName("MemoryPack.CallSite.1_TypeArguments");

        var source = callSiteTypes
            .Combine(context.CompilationProvider);

        context.RegisterSourceOutput(source, static (context, source) =>
        {
            var (types, compilation) = source;
            if (types.IsDefaultOrEmpty) return;
            if (compilation.GetTypeByMetadataName("System.Runtime.CompilerServices.ModuleInitializerAttribute") == null) return;
            if (compilation.GetTypeByMetadataName("MemoryPack.MemoryPackFormatterProvider") == null) return;

            var reference = new ReferenceSymbols(compilation);
            var collector = new TypeCollector();
            foreach (var type in types)
            {
                collector.Visit(type!, false);
            }

            var registrations = new SortedDictionary<string, string>(StringComparer.Ordinal);
            foreach (var type in collector.GetTypes())
            {
                if (type.IsUnmanagedType) continue;
                if (!IsNameable(type, compilation)) continue;

                var formatter = reference.KnownTypes.GetNonDefaultFormatterName(type);
                if (formatter == null) continue;

                registrations[type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)] = formatter;
            }

            if (registrations.Count == 0) return;

            var sb = new StringBuilder();
            sb.AppendLine("""
// <auto-generated/>
#nullable enable
#pragma warning disable CA2255
#pragma warning disable CS8631

namespace MemoryPack.Generated
{
    internal static class MemoryPackCallSiteRegistration
    {
        [global::System.Runtime.CompilerServices.ModuleInitializer]
        internal static void Register()
        {
""");
            foreach (var item in registrations)
            {
                sb.AppendLine($"            if (!global::MemoryPack.MemoryPackFormatterProvider.IsRegistered<{item.Key}>()) global::MemoryPack.MemoryPackFormatterProvider.Register(new {item.Value}());");
            }
            sb.AppendLine("""
        }
    }
}
""");
            context.AddSource("MemoryPack.CallSiteRegistration.g.cs", sb.ToString());
        });
    }

    static string? InvokedName(ExpressionSyntax expression)
    {
        return expression switch
        {
            MemberAccessExpressionSyntax memberAccess => memberAccess.Name.Identifier.ValueText,
            GenericNameSyntax generic => generic.Identifier.ValueText,
            IdentifierNameSyntax identifier => identifier.Identifier.ValueText,
            _ => null,
        };
    }

    // Whether generated code in this assembly can write the type's name: no type parameters, no
    // anonymous, pointer or file-local types, and every named type accessible from here.
    static bool IsNameable(ITypeSymbol type, Compilation compilation)
    {
        switch (type)
        {
            case IArrayTypeSymbol array:
                return IsNameable(array.ElementType, compilation);
            case INamedTypeSymbol named:
                if (named.IsAnonymousType || named.IsUnboundGenericType) return false;
                if (!compilation.IsSymbolAccessibleWithin(named, compilation.Assembly)) return false;
                for (var t = named; t != null; t = t.ContainingType)
                {
                    foreach (var syntaxReference in t.DeclaringSyntaxReferences)
                    {
                        if (syntaxReference.GetSyntax() is TypeDeclarationSyntax declaration && declaration.Modifiers.Any(x => x.Text == "file")) return false;
                    }
                }
                foreach (var argument in named.TypeArguments)
                {
                    if (!IsNameable(argument, compilation)) return false;
                }
                return named.ContainingType == null || IsNameable(named.ContainingType, compilation);
            default:
                return false;
        }
    }
}
